"""Generate the portable film-rebate text outlines from two Liberation Sans faces.

Run with FontTools plus unmodified LiberationSans Regular and Bold TTFs, with
the paths as arguments. The derived glyph subset is named Argentroom Edge.
"""
import sys
from fontTools.pens.basePen import BasePen
from fontTools.ttLib import TTFont


class OutlinePen(BasePen):
    def __init__(self, glyphs):
        super().__init__(glyphs)
        self.contours = []

    def _moveTo(self, point):
        self.contours.append([point])

    def _lineTo(self, point):
        self.contours[-1].append(point)

    def _qCurveToOne(self, control, end):
        start = self.contours[-1][-1]
        for step in range(1, 9):
            t = step / 8
            u = 1 - t
            self._lineTo(tuple(
                u * u * start[k] + 2 * u * t * control[k] + t * t * end[k]
                for k in range(2)
            ))


print("// Argentroom Edge glyph outlines. SIL-OFL-1.1; see assets/legal/silverphase/ARGENTROOM-EDGE-OFL.txt.")
print("// Generated by tools/silverphase/film_edge_outline.py.")
for face, path in zip(("Regular", "Bold"), sys.argv[1:], strict=True):
    font = TTFont(path)
    glyphs = font.getGlyphSet()
    cmap = font.getBestCmap()
    units = font["head"].unitsPerEm
    points = []
    records = []
    for code in range(32, 127):
        glyph = glyphs[cmap[code]]
        pen = OutlinePen(glyphs)
        glyph.draw(pen)
        start = len(points)
        for contour in pen.contours:
            points.extend((round(x * 2048 / units), round(y * 2048 / units))
                          for x, y in contour)
            points.append((32767, 0))
        records.append((start, len(points), round(glyph.width * 2048 / units)))

    print(f"constexpr GlyphSpec kEdge{face}Glyphs[] = {{")
    for start, end, advance in records:
        print(f"    {{{start}, {end}, {advance}}},")
    print("};")
    print(f"constexpr GlyphPoint kEdge{face}Points[] = {{")
    for i in range(0, len(points), 8):
        print("    " + ", ".join(f"{{{x},{y}}}" for x, y in points[i:i+8]) + ",")
    print("};")
